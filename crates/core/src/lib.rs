pub mod db;
pub mod migrations;

use serde::{Deserialize, Serialize};
use specta::Type;

#[derive(Debug, Clone, Serialize, Deserialize, Type)]
pub struct PingPayload {
    pub message: Option<String>,
}

#[derive(Debug, Clone, Serialize, Deserialize, Type)]
pub struct PingResponse {
    pub status: String,
    pub database_status: String,
    pub database_path: String,
    pub roundtrip_timestamp: String,
    pub echo: Option<String>,
}

#[derive(Debug, Clone, Serialize, Deserialize, Type)]
pub struct RpcError {
    pub code: String,
    pub message: String,
    pub field: Option<String>,
}

#[derive(Debug, Clone, Serialize, Deserialize, Type)]
pub struct RpcEnvelope<T> {
    pub ok: bool,
    pub data: Option<T>,
    pub error: Option<RpcError>,
}

pub fn handle_rpc(command: &str, payload_json: &str) -> String {
    match command {
        "system.ping" => {
            let payload: PingPayload =
                serde_json::from_str(payload_json).unwrap_or(PingPayload { message: None });
            match db::run_ping_transaction(payload.message.clone()) {
                Ok((db_status, pinged_at, echo_details)) => {
                    let db_path = db::resolve_dev_db_path()
                        .map(|p| p.display().to_string())
                        .unwrap_or_else(|_| "unknown".to_string());
                    let response = RpcEnvelope {
                        ok: true,
                        data: Some(PingResponse {
                            status: "ok".to_string(),
                            database_status: db_status,
                            database_path: db_path,
                            roundtrip_timestamp: pinged_at,
                            echo: Some(echo_details),
                        }),
                        error: None,
                    };
                    serde_json::to_string(&response).unwrap()
                }
                Err(err) => {
                    let response: RpcEnvelope<PingResponse> = RpcEnvelope {
                        ok: false,
                        data: None,
                        error: Some(RpcError {
                            code: "database_error".to_string(),
                            message: err.to_string(),
                            field: None,
                        }),
                    };
                    serde_json::to_string(&response).unwrap()
                }
            }
        }
        _ => {
            let response: RpcEnvelope<()> = RpcEnvelope {
                ok: false,
                data: None,
                error: Some(RpcError {
                    code: "unknown_command".to_string(),
                    message: format!("Unknown command: {}", command),
                    field: None,
                }),
            };
            serde_json::to_string(&response).unwrap()
        }
    }
}

pub fn generate_ts_definitions() -> String {
    r#"/**
 * Auto-generated by Coachify xtask export-types.
 * UI <-> Core boundary contract. Do not edit manually.
 */

import { invoke } from "@tauri-apps/api/core";

export interface PingPayload {
  message?: string | null;
}

export interface PingResponse {
  status: string;
  database_status: string;
  database_path: string;
  roundtrip_timestamp: string;
  echo?: string | null;
}

export interface RpcError {
  code: string;
  message: string;
  field?: string | null;
}

export interface RpcEnvelope<T> {
  ok: boolean;
  data?: T;
  error?: RpcError;
}

export interface CommandMap {
  "system.ping": {
    request: PingPayload;
    response: PingResponse;
  };
}

export type CommandName = keyof CommandMap;

/**
 * Single typed RPC entry point to the Rust core.
 */
export async function rpc<C extends CommandName>(
  command: C,
  payload: CommandMap[C]["request"],
  idempotencyKey?: string
): Promise<RpcEnvelope<CommandMap[C]["response"]>> {
  try {
    const raw = await invoke<string | RpcEnvelope<CommandMap[C]["response"]>>("rpc", {
      command,
      payload,
      idempotencyKey: idempotencyKey ?? null,
    });
    if (typeof raw === "string") {
      return JSON.parse(raw);
    }
    return raw;
  } catch (err: unknown) {
    return {
      ok: false,
      error: {
        code: "transport_error",
        message: err instanceof Error ? err.message : String(err),
      },
    };
  }
}
"#
    .to_string()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_system_ping_roundtrip() {
        let payload = serde_json::to_string(&PingPayload {
            message: Some("test_ping".to_string()),
        })
        .unwrap();

        let response_str = handle_rpc("system.ping", &payload);
        let envelope: RpcEnvelope<PingResponse> = serde_json::from_str(&response_str).unwrap();

        assert!(envelope.ok);
        let data = envelope.data.expect("data should be present");
        assert_eq!(data.status, "ok");
        assert_eq!(data.database_status, "active");
        assert!(data.echo.unwrap().contains("test_ping"));
    }

    #[test]
    fn test_unknown_command() {
        let response_str = handle_rpc("nonexistent.command", "{}");
        let envelope: RpcEnvelope<()> = serde_json::from_str(&response_str).unwrap();
        assert!(!envelope.ok);
        let error = envelope.error.expect("error should be present");
        assert_eq!(error.code, "unknown_command");
    }
}
